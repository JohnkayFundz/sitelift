import { createClient } from "@supabase/supabase-js";
export function supabaseAdmin() {
  const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error("Missing Supabase server configuration");
  return createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
}
export function json(res, status, body) {
  res.status(status); res.setHeader("Content-Type", "application/json; charset=utf-8");
  res.setHeader("Cache-Control", "no-store"); res.setHeader("X-Content-Type-Options", "nosniff");
  return res.json(body);
}
export function escapePdfText(value) {
  return String(value ?? "").replace(/[^\x20-\x7E]/g, " ").replace(/([\\()])/g, "\\$1").slice(0, 180);
}
export function createAuditPdf(audit) {
  const lines = ["SiteLift - Website Audit Report", "Website: " + (audit.final_url || audit.target_url), "Device: " + audit.strategy, "Audited: " + new Date(audit.created_at).toISOString(), "", "LIGHTHOUSE SCORES", ...(audit.report.scores || []).map((s) => s.label + ": " + (s.value ?? "N/A") + "/100"), "", "KEY METRICS", ...(audit.report.metrics || []).map((m) => m.label + ": " + m.value), "", "PRIORITIZED RECOMMENDATIONS", ...(audit.report.opportunities || []).slice(0, 8).map((o, i) => (i + 1) + ". " + o.title + " - " + (o.displayValue || "Review recommended")), "", "Scores are lab measurements and may vary between runs.", "Generated by SiteLift | https://sitelift.vercel.app"];
  const commands = ["BT", "/F1 10 Tf", "50 790 Td", "13 TL"];
  lines.forEach((line, index) => { if (index) commands.push("T*"); commands.push("(" + escapePdfText(line) + ") Tj"); });
  commands.push("ET"); const stream = commands.join("\n");
  const objects = ["<< /Type /Catalog /Pages 2 0 R >>", "<< /Type /Pages /Kids [3 0 R] /Count 1 >>", "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>", "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>", "<< /Length " + Buffer.byteLength(stream, "utf8") + " >>\nstream\n" + stream + "\nendstream"];
  let pdf = "%PDF-1.4\n"; const offsets = [0];
  objects.forEach((object, index) => { offsets.push(Buffer.byteLength(pdf, "utf8")); pdf += (index + 1) + " 0 obj\n" + object + "\nendobj\n"; });
  const xref = Buffer.byteLength(pdf, "utf8"); pdf += "xref\n0 " + (objects.length + 1) + "\n0000000000 65535 f \n";
  offsets.slice(1).forEach((offset) => { pdf += String(offset).padStart(10, "0") + " 00000 n \n"; });
  pdf += "trailer\n<< /Size " + (objects.length + 1) + " /Root 1 0 R >>\nstartxref\n" + xref + "\n%%EOF";
  return Buffer.from(pdf, "utf8");
}
